import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { JSDOM } from 'jsdom';

async function setup() {
  const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost/#sim', runScripts: 'dangerously', pretendToBeVisual: true });
  const { window } = dom;
  window.scrollTo = () => {};
  const originalTimer = window.setTimeout.bind(window);
  window.setTimeout = (fn, delay, ...args) => originalTimer(fn, delay >= 650 ? delay / 5 : delay, ...args);
  const errors = [];
  window.addEventListener('error', e => errors.push(e.message));
  const bundle = readdirSync(new URL('../dist/assets/', import.meta.url)).find(f => f.endsWith('.js'));
  window.eval(readFileSync(new URL(`../dist/assets/${bundle}`, import.meta.url), 'utf8'));
  const settle = (ms = 35) => new Promise(resolve => setTimeout(resolve, ms));
  const doc = window.document;
  const button = text => [...doc.querySelectorAll('button')].find(el => el.textContent.includes(text));
  const click = async el => { assert.ok(el, 'Expected interactive element'); el.click(); await settle(); };
  const edit = async (label, text) => {
    const el = doc.querySelector(`[aria-label="${label}"]`) || doc.getElementById(label);
    assert.ok(el, `Expected editor ${label}`);
    const prototype = el.tagName === 'TEXTAREA' ? window.HTMLTextAreaElement.prototype : el.tagName === 'SELECT' ? window.HTMLSelectElement.prototype : window.HTMLInputElement.prototype;
    Object.getOwnPropertyDescriptor(prototype, 'value').set.call(el, text);
    el.dispatchEvent(new window.Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true }));
    await settle();
  };
  const upload = async name => {
    const input = doc.querySelector('input[type=file]');
    Object.defineProperty(input, 'files', { value: [new window.File(['test'], name)], configurable: true });
    input.dispatchEvent(new window.Event('change', { bubbles: true }));
    await settle();
  };
  await settle();
  return { dom, window, doc, button, click, edit, upload, settle, errors };
}

